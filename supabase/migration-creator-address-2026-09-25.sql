-- ============================================================
-- 起案者住所を AIツールのヒアリングに追加（t iku指示 2026-09-25）
--
-- 何のための列か:
--   KAMO事務局からの連絡・書類送付に使う **起案者本人の住所**。
--   メールアドレス・電話番号と同じ扱いで、
--   🔴 掲載用JSON（page列）・PDF・AIへの送信内容には一切含めない。
--   個人情報なので、管理画面でのみ表示する。
--
-- 実行方法:
--   Supabase のダッシュボード → SQL Editor にこのファイルの内容を貼り付けて Run。
--   何度実行しても安全です（IF NOT EXISTS のため）。
--
-- 実行しなかった場合:
--   アプリは落ちません。住所だけが保存されずスキップされます
--   （/api/ai/submit が列の欠落を検知して、列なしで保存し直します）。
-- ============================================================

ALTER TABLE ai_generations
  ADD COLUMN IF NOT EXISTS contact_address TEXT;

COMMENT ON COLUMN ai_generations.contact_address IS
  'ヒアリングで入力された起案者住所（事務局の連絡・書類送付用）。掲載用JSON・PDF・AI生成には使用しない。';
