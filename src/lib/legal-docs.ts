/**
 * 法務ページを公開してよいか。
 *
 * 未公開のあいだは各ページが notFound() を返し、フッターのリンクも描画しない。
 * noindex ではなく 404 を選んでいるのは、URLが漏れた場合に
 * 「矛盾した規約が読める」状態を作らないため。
 */
export function isLegalPublished(): boolean {
  return process.env.NEXT_PUBLIC_LEGAL_PAGES_PUBLISHED === 'true';
}

