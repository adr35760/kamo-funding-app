/**
 * /success に掲載する事例（6項目のテンプレートで書き切れるもの）。
 */
export interface CaseStory {
  /** 本家プロジェクトページのスラッグ */
  slug: string;
  /** カテゴリ3のサブ分類（店舗／出版／地域活動）。カテゴリ1・2では未設定 */
  subLabel?: string;
  /** 見出し（「〇〇したい。」の一文） */
  heading: string;
  /** プロジェクト名（本家ページの表記） */
  title: string;
  /** 実行者名（本家ページの表記に「さん」を付けたもの） */
  owner: string;
  /** 実行者の肩書・補足（本家ページの表記のみ） */
  ownerNote?: string;
  /** カードに出す1行の要約（ページ記載の範囲で要約） */
  summary: string;
  /** プロジェクトのメイン画像があるか（無い場合は画像枠ごと出さない） */
  hasImage?: boolean;

  /** ① 挑戦の背景（なぜ始めたのか） */
  background: string;
  /** ② 企画内容（何を実現しようとしたのか） */
  plan: string;
  /** ② 企画内容の要点（ページ記載の範囲・任意） */
  planPoints?: string[];
  /** ③ 支援の工夫（何を工夫したのか・箇条書き） */
  effort: string[];

  /** ④ 目標金額（円） */
  goal: number;
  /** ④ 集まった金額（円） */
  raised: number;
  /** ④ 支援数（ページの「支援数」） */
  supporters: number;
  /** ④ 達成率（%） */
  achievementRate: number;
  /** ④ 終了日（ページの「このプロジェクトはYYYY/MM/DDに終了」） */
  endDate: string;
  /** ④ 募集期間（開始日と終了日の両方がページに書かれている場合のみ） */
  period?: string;

  /** ⑤ 成功のポイント（ページ記載の取り組みから整理した3点） */
  successPoints: string[];
  /** 実行者のコメント（ページに書かれている範囲・任意） */
  voice?: string;
  /** コメントの出典表記（例「終了後の報告より」） */
  voiceSource?: string;
  /**
   * コメントの種類（引用の上に出す小さなラベル）。
   * 2026-11-22 t iku指示: 「実行者の感想」と一括りにすると、
   * 実施前の想いまで実施後の感想に見えるため、出典と本文に合わせて分ける。
   * 出典が実施前（プロフィール・メッセージ・開始前の想い）→ 実行者の想い
   * 終了後・達成・活動報告 → 実施後の報告
   * 実施後の気持ち・振り返り → 実施後の感想
   * 実施中（終了前）の報告 → 実施中の報告
   */
  voiceLabel?: VoiceLabel;
}

/** 引用ラベルの種類 */
export type VoiceLabel =
  | '実施後の報告'
  | '実施後の感想'
  | '実行者の想い'
  | '実施中の報告'
  | '実行者の言葉';

